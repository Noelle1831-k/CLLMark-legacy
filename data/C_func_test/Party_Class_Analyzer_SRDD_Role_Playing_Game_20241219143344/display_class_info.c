void display_class_info(Class *class) {
    printf("Class Name: %s\n", class->name);
    printf("Strength: %d\n", class->strength);
    printf("Intelligence: %d\n", class->intelligence);
    printf("Agility: %d\n", class->agility);
    printf("Defense: %d\n", class->defense);
    printf("Attack: %d\n", class->attack);
}