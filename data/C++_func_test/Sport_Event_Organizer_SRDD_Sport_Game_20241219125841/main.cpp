int main(void) {
    Event event;
    Schedule schedule;
    Team teamManager;
    Referee refereeManager;
    Participant participantManager;
    GameProgress gameProgressManager;
    Report reportManager;
    printf("Setting event details...\n");
    event.setDetails("2023-12-01", "10:00 AM", "Stadium A", "Soccer");
    cout << "Event Details:\n" << event.getDetails() << endl;
    printf("Registering participants...\n");
    participantManager.registerParticipant("John Doe");
    participantManager.registerParticipant("Jane Smith");
    printf("Participants Registered:\n");
    participantManager.getParticipants();
    printf("Adding teams...\n");
    teamManager.addTeam("Team A");
    teamManager.addTeam("Team B");
    printf("Teams Registered:\n");
    teamManager.getTeams();
    printf("Assigning referees...\n");
    refereeManager.assignReferees({"Referee 1", "Referee 2"});
    printf("Referees Assigned:\n");
    refereeManager.getReferees();
    printf("Generating schedule...\n");
    schedule.generateSchedule(event, teamManager, refereeManager);
    printf("Schedule:\n");
    schedule.displaySchedule();
    printf("Updating game progress...\n");
    gameProgressManager.updateProgress("Match 1", "In Progress");
    gameProgressManager.updateProgress("Match 2", "Completed");
    printf("Game Progress:\n");
    gameProgressManager.getProgress();
    printf("Generating event report...\n");
    reportManager.generateReport(event, teamManager, refereeManager, gameProgressManager);
    printf("Event Report:\n");
    reportManager.displayReport();
    return 0;
}