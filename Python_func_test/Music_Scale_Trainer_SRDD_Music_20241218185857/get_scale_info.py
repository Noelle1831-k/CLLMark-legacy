def get_scale_info(self, scale_name):
        if scale_name == "C Major":
            return "C Major scale consists of the notes: C, D, E, F, G, A, B."
        elif scale_name == "A Minor":
            return "A Minor scale consists of the notes: A, B, C, D, E, F, G."
        else:
            return "Scale information not available."