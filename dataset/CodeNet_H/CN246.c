int f[10];
int ans, sum, tmp;
int pair[29][4][2] = {
{{1,1},{4,1},{5,1}}, {{2,1},{3,1},{5,1}}, {{2,1},{4,2}}, {{3,2},{4,1}},
{{1,2},{3,1},{5,1}}, {{1,2},{4,2}}, {{1,1},{2,2},{5,1}}, {{1,1},{2,1},{3,1},{4,1}},
{{1,1},{3,3}}, {{2,3},{4,1}}, {{2,2},{3,2}}, {{1,3},{2,1},{5,1}}, {{1,3},{3,1},{4,1}},
{{1,2},{2,2},{4,1}}, {{1,2},{2,1},{3,2}}, {{1,1},{2,3},{3,1}}, {{2,5}}, {{1,5},{5,1}},
{{1,4},{2,1},{4,1}}, {{1,4},{3,2}}, {{1,3},{2,2},{3,1}}, {{1,2},{2,4}}, {{1,6},{4,1}},
{{1,5},{2,1},{3,1}}, {{1,4},{2,3}}, {{1,7},{3,1}}, {{1,6},{2,2}}, {{1,8},{2,1}}, {{1,10}} };
int take(int k)
{
	int i, a, b;
	for (i = 0; (a = pair[k][i][0]) > 0; i++) {
		b = pair[k][i][1];
		if (f[a] < b) return 0;
	}
	for (i = 0; (a = pair[k][i][0]) > 0; i++) f[a] -= pair[k][i][1];
	sum -= 10; tmp++;
	return 1;
}
void back(int k)
{
	int i, a;
	for (i = 0; (a = pair[k][i][0]) > 0; i++) f[a] += pair[k][i][1];
	sum += 10; tmp--;
}
void rec(int k)
{
	int i;
	if (sum >= 10) for (i = k; i < 29; i++) if (take(i)) rec(i), back(i);
	if (tmp > ans) ans = tmp;
}
int main()
{
	int n, i, k;
	while (scanf("%d", &n) && n > 0) {
		memset(f, 0, sizeof(f));
		while (n-- > 0) scanf("%d", &k), f[k]++;
		for (ans = 0, i = 9; i >= 6; i--) {
			k = f[i]; if (f[10-i] < k) k = f[10-i];
			ans += k, f[i] -= k, f[10-i] -= k;
		}
		ans += f[5]/2, f[5] &= 1;
		f[9] = 0;
		if (f[8] > 0) {
			if (f[1] >= 2*f[8]) ans += f[8], f[1] -= 2*f[8];
			else if (f[1] & 1) ans += f[1]/2, f[1] = 1;
			else               ans += f[1]/2, f[1] = 0;
			f[8] = 0;
		}
		if (f[7] > 0) {
			while (f[7] > 0 && f[1] > 0 && f[2] > 0) ans++, f[7]--, f[1]--, f[2]--;
			while (f[7] > 0 && f[1] >= 3) ans++, f[7]--, f[1]-=3;
			f[7] = 0;
		}
		if (f[6] > 0) {
			while (f[6] > 0 && f[1] >  0 && f[3] > 0) ans++, f[6]--, f[1]--, f[3]--;
			while (f[6] > 0 && f[2] >= 2) ans++, f[6]--, f[2]-=2;
			while (f[6] > 0 && f[1] >= 2 && f[2] > 0) ans++, f[6]--, f[1]-=2, f[2]--;
			while (f[6] > 0 && f[1] >= 4) ans++, f[6]--, f[1]-=4;
			f[6] = 0;
		}
		for (sum = 0, i = 1; i <= 5; i++) sum += i*f[i];
		tmp = ans;
		rec(0);
		printf("%d\n", ans);
	}
	return 0;
}