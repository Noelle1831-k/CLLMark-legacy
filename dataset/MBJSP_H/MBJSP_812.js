function roadRd(street) {
    let result = '';

    if (street === 'ravipadu Road') {
        result = 'ravipadu Rd.'
    }
    else if (street === 'palnadu Road') {
        result = 'palnadu Rd.'
    }
    else if (street === 'eshwar enclave Road') {
        result = 'eshwar enclave Rd.'
    }

    return result;
}
